

class Calculator:
    def __init__(self):
        self.result = 0

    def multiply(self, num1, num2):
        self.result = num1 * num2
        return self.result

    def add(self, num3, num4):
        self.result = num3 + num4
        return self.result

    def subtract(self, num5, num6):
        self.result = num5 - num6
        return self.result

    def divide(self, num7, num8):
        self.result = num7 / num8
        return self.result

